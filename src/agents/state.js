'use strict';

/**
 * Shared LangGraph State
 *
 * This object is passed between all agents in the graph.
 * Each agent reads from it, appends its results, and returns
 * a partial update that LangGraph merges back.
 */

const { Annotation, messagesStateReducer } = require('@langchain/langgraph');

/**
 * ResearchState — the single shared state object flowing through the graph.
 *
 * Fields:
 *  messages         – LangChain message thread (supervisor + agent turns)
 *  lessonTitle      – lesson being researched
 *  learningObjective
 *  lessonId         – optional MongoDB Lesson _id
 *  sessionId        – MongoDB ResearchSession _id (set after session created)
 *  executionId      – MongoDB AgentExecution _id
 *
 *  queries          – { web, book, youtube } string arrays generated by supervisor
 *
 *  webResults       – raw results from web agent
 *  bookResults      – raw results from book agent
 *  youtubeResults   – raw results from YouTube agent
 *
 *  providerStatus   – { web, book, youtube } → 'pending'|'running'|'done'|'failed'
 *  errors           – accumulated error messages from any agent
 *
 *  stepLog          – array of { agent, action, reasoning, observation, durationMs }
 *  tokenUsage       – accumulated { promptTokens, completionTokens }
 *
 *  iterationCount   – number of supervisor decision loops
 *  finalResult      – combined result object saved at the end
 *  isComplete       – boolean flag; set to true when supervisor decides we're done
 */

const ResearchState = Annotation.Root({
  // Message thread (uses built-in reducer that appends messages)
  messages: Annotation({
    reducer: messagesStateReducer,
    default: () => [],
  }),

  // Lesson context
  lessonTitle:        Annotation({ reducer: (_, v) => v, default: () => '' }),
  learningObjective:  Annotation({ reducer: (_, v) => v, default: () => '' }),
  lessonId:           Annotation({ reducer: (_, v) => v, default: () => null }),

  // MongoDB IDs
  sessionId:    Annotation({ reducer: (_, v) => v, default: () => null }),
  executionId:  Annotation({ reducer: (_, v) => v, default: () => null }),

  // Research queries (supervisor writes once)
  queries: Annotation({
    reducer: (prev, next) => ({ ...prev, ...next }),
    default: () => ({ web: [], book: [], youtube: [] }),
  }),

  // Research results (each agent appends)
  webResults:     Annotation({ reducer: (_, v) => v, default: () => [] }),
  bookResults:    Annotation({ reducer: (_, v) => v, default: () => [] }),
  youtubeResults: Annotation({ reducer: (_, v) => v, default: () => [] }),

  // Provider pipeline status
  providerStatus: Annotation({
    reducer: (prev, next) => ({ ...prev, ...next }),
    default: () => ({ web: 'pending', book: 'pending', youtube: 'pending' }),
  }),

  // Error accumulator (append-only)
  errors: Annotation({
    reducer: (prev, next) => [...prev, ...next],
    default: () => [],
  }),

  // Execution trace
  stepLog: Annotation({
    reducer: (prev, next) => [...prev, ...next],
    default: () => [],
  }),

  // Token usage accumulator
  tokenUsage: Annotation({
    reducer: (prev, next) => ({
      promptTokens:     (prev.promptTokens     || 0) + (next.promptTokens     || 0),
      completionTokens: (prev.completionTokens || 0) + (next.completionTokens || 0),
    }),
    default: () => ({ promptTokens: 0, completionTokens: 0 }),
  }),

  // Control flow
  iterationCount: Annotation({ reducer: (_, v) => v, default: () => 0 }),
  finalResult:    Annotation({ reducer: (_, v) => v, default: () => null }),
  isComplete:     Annotation({ reducer: (_, v) => v, default: () => false }),
});

module.exports = { ResearchState };

